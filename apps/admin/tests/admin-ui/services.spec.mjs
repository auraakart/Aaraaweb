import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const a = '11111111-1111-4111-8111-111111111111'
async function checklist(page) {
  await page.getByLabel('Service offering').selectOption(a)
  await page.getByRole('button', { name: 'Load checklist', exact: true }).click()
}
test('provider edits exact version and keeps historical bookings unchanged', async ({ page }) => {
  await page.goto('/services.html')
  expect(await page.evaluate(() => window.serviceRequests)).toHaveLength(0)
  await checklist(page)
  await page.getByLabel('Step label 1', { exact: true }).fill('Inspect filter safely')
  await page.getByRole('button', { name: 'Save checklist', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Existing bookings keep their original checklist')
  const write = (await page.evaluate(() => window.serviceRequests)).find(r => r.method === 'PUT')
  expect(write.body).toEqual({ expectedVersion: 2, items: [{ id: 'inspect_filter', label: 'Inspect filter safely', required: true }] })
  await page.getByRole('button', { name: 'Refresh quality activity' }).click()
  await expect(page.getByText('Completed with a captured checklist')).toBeVisible()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
})
test('provider conflict requires reload and changing offering clears editing state', async ({ page }) => {
  await page.goto('/services.html?conflict'); await checklist(page)
  await page.getByRole('button', { name: 'Save checklist', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Reload before saving again')
  await expect(page.getByRole('button', { name: 'Save checklist', exact: true })).toHaveCount(0)
  expect((await page.evaluate(() => window.serviceRequests)).filter(r => r.method === 'PUT')).toHaveLength(1)
  await page.getByLabel('Service offering').selectOption('22222222-2222-4222-8222-222222222222')
  await expect(page.getByLabel('Step label 1', { exact: true })).toHaveCount(0)
})
test('agent records explicit failing evidence against its own assignment', async ({ page }) => {
  await page.goto('/services.html?mode=agent')
  await page.getByLabel('My assignment').selectOption(a)
  await page.getByRole('button', { name: 'Refresh assignment checklist' }).click()
  await expect(page.getByRole('button', { name: 'Record Inspect filter' })).toBeDisabled()
  await page.getByLabel('Assessment for Inspect filter').selectOption('fail')
  await page.getByLabel('Note for Inspect filter').fill('Filter needs attention')
  await page.getByRole('button', { name: 'Record Inspect filter' }).click()
  await expect(page.getByText('Latest recorded assessment: Needs attention')).toBeVisible()
  const writes = (await page.evaluate(() => window.serviceRequests)).filter(r => r.method === 'POST')
  expect(writes).toHaveLength(1)
  expect(writes[0].path).toContain(`/assignments/${a}/quality-evidence`)
  expect(writes[0].body).toEqual({ itemId: 'inspect_filter', passed: false, note: 'Filter needs attention' })
})
test('foreign or denied agent access exposes no assessment writes', async ({ page }) => {
  await page.goto('/services.html?mode=agent&foreign')
  await page.getByLabel('My assignment').selectOption(a)
  await page.getByRole('button', { name: 'Refresh assignment checklist' }).click()
  await expect(page.getByRole('alert')).toContainText('Invalid assignment checklist')
  await expect(page.getByRole('button', { name: 'Record Inspect filter' })).toHaveCount(0)
  await page.goto('/services.html?mode=agent&denied')
  await expect(page.getByRole('alert')).toContainText('Field-agent access')
  expect((await page.evaluate(() => window.serviceRequests)).some(r => r.method === 'POST')).toBe(false)
})
test('dispatch requires confirmation and stops repeat assignment after success', async ({ page }) => {
  await page.goto('/services.html?mode=dispatch')
  await page.getByRole('button', { name: 'Refresh dispatch', exact: true }).click()
  await expect(page.getByText(/Ravi · No recorded schedule conflict/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirm quick dispatch' })).toBeDisabled()
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Confirm quick dispatch' }).click()
  await expect(page.getByRole('status')).toContainText('Technician assigned')
  await expect(page.getByRole('button', { name: 'Confirm quick dispatch' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Refresh dispatch', exact: true }).click()
  await expect(page.getByText('An active assignment already exists. Quick dispatch is unavailable.')).toBeVisible()
  expect((await page.evaluate(() => window.serviceRequests)).filter(r => r.method === 'POST')).toHaveLength(1)
})
test('dispatch refuses overlap and reads server state after lost response', async ({ page }) => {
  await page.goto('/services.html?mode=dispatch&overlap')
  await page.getByRole('button', { name: 'Refresh dispatch', exact: true }).click()
  await page.getByRole('checkbox').check()
  await expect(page.getByRole('button', { name: 'Confirm quick dispatch' })).toBeDisabled()
  await page.goto('/services.html?mode=dispatch&lost')
  await page.getByRole('button', { name: 'Refresh dispatch', exact: true }).click()
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Confirm quick dispatch' }).click()
  await expect(page.getByRole('alert')).toContainText('Refresh dispatch before another attempt')
  await page.getByRole('button', { name: 'Refresh dispatch', exact: true }).click()
  await expect(page.getByText('An active assignment already exists. Quick dispatch is unavailable.')).toBeVisible()
  expect((await page.evaluate(() => window.serviceRequests)).filter(r => r.method === 'POST')).toHaveLength(1)
})
