import { test,expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
async function confirm(page){await page.getByRole('button',{name:'Confirm',exact:true}).click()}
test('licensing requires explicit opt-in and separates approval from activation',async({page})=>{
 await page.goto('/licensing.html');await page.getByLabel('Decision reason').fill('Reviewed commercial plan')
 await page.getByRole('button',{name:'Approve commercial license'}).click();await confirm(page)
 await expect(page.getByRole('button',{name:'Record society opt-in'})).toBeDisabled()
 await page.getByRole('checkbox').check();await page.getByRole('button',{name:'Record society opt-in'}).click();await confirm(page)
 await page.getByRole('button',{name:'Activate society allocation'}).click();await confirm(page)
 await expect(page.getByText(/Allocation: Active/)).toBeVisible()
 const requests=await page.evaluate(()=>window.licensingRequests)
 expect(requests.map(r=>r.path.split('/').at(-1))).toEqual(['approvals','consents','allocations'])
 expect(requests[0].body.essentialPolicy).toBe('PRESERVE_LEGACY')
 expect(requests[1].body.expectedFeatures).toContain('SOS')
 expect(requests[2].body.consentId).toBe('55555555-5555-4555-8555-555555555555')
})
test('licensing society admin cannot approve, revoke, activate or see partner-wide usage',async({page})=>{
 await page.goto('/licensing.html?mode=approved&role=SOCIETY_ADMIN')
 await expect(page.getByRole('button',{name:'Record society opt-in'})).toBeVisible()
 await expect(page.getByRole('button',{name:'Approve commercial license'})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Revoke commercial license'})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Activate society allocation'})).toHaveCount(0)
 await expect(page.getByText(/Approved allocation capacity:/)).toHaveCount(0)
})
test('licensing lost-response retry preserves the exact idempotency key',async({page})=>{
 await page.goto('/licensing.html?mode=response-lost')
 await page.getByRole('button',{name:'Activate society allocation'}).click();await confirm(page)
 await expect(page.getByRole('alert')).toContainText('Response lost')
 await page.getByRole('button',{name:'Activate society allocation'}).click();await confirm(page)
 await expect(page.getByText(/Allocation: Active/)).toBeVisible()
 const requests=await page.evaluate(()=>window.licensingRequests)
 expect(requests).toHaveLength(2);expect(requests[0].body).toEqual(requests[1].body)
})
test('licensing discards late old-society responses after context switch',async({page})=>{
 await page.goto('/licensing.html?mode=stale')
 await page.waitForFunction(()=>typeof window.resolveFirstLicensingOverview==='function')
 await page.evaluate(()=>window.changeLicensingContext())
 await expect(page.getByText('Second society',{exact:true})).toBeVisible()
 await page.evaluate(()=>window.resolveFirstLicensingOverview())
 await expect(page.getByText('First society',{exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Approve commercial license'})).toBeVisible()
})
test('licensing controls stay accessible at mobile width',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/licensing.html?mode=approved')
 await expect(page.getByRole('button',{name:'Record society opt-in'})).toBeVisible()
 const results=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
 expect(results.violations).toEqual([])
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})
